    <h2>Links</h2>
    <p>Every CV has its own address. Copy it from the CV page with <strong>Copy link</strong>. Change the address under <strong>Look and privacy</strong> if you want something shorter.</p>

    <h2>QR codes</h2>
    <p>Each CV has a QR code for printed copies, posters and business cards. Scans are counted separately in your analytics, so you can tell when a printed CV is working.</p>

    <h2>PDFs</h2>
    <p><strong>Download PDF</strong> builds a print-ready PDF in the same theme, accent colour and section order. Links are printed out in full so they still work on paper. The PDF is tagged for screen readers: it has its own title, its headings show as bookmarks and its lists and links are marked as real lists and links. A cover letter's PDF works the same way.</p>

    <h2>Share previews</h2>
    <p>When your link is posted on a social site or in a chat, a preview card shows your photo, name, headline and top skills.</p>

    <h2>Messages from visitors</h2>
    <p>Visitors can send you a message from your CV without ever seeing your email address. You receive it by email and only share your address if you choose to reply.</p>
