    <h2>Create your account</h2>
    <ol>
        <li>Select <strong>Create your CV</strong> at the top of any page.</li>
        <li>Enter your name, email address and a password of at least 10 characters with a letter and a number. You can also continue with Google, GitHub, Microsoft or LinkedIn where they are offered.</li>
        <li>Open the confirmation email and select the link. Nothing can be created until your email address is confirmed.</li>
    </ol>
    <p>Your first CV, called <strong>My CV</strong>, is ready straight away on the <strong>My CVs</strong> page.</p>

    <h2>Set up your profile</h2>
    <p>Your profile holds what every CV shares: your photo, headline, bio, location, university, availability and links. Open <strong>Settings</strong> from the account menu in the top corner to fill it in.</p>

    <h2>Build your first CV</h2>
    <p>Open your CV from <strong>My CVs</strong>. Each CV has five tabs: Content, Projects, File and LaTeX, Look and privacy, then Import and export. Start with Content, then choose a theme and who can see the CV under Look and privacy.</p>

    <h2>Keep more than one version</h2>
    <p>Most people tailor a CV for each kind of role. Create up to ten CVs, each with its own name, address and privacy setting. Duplicating a CV from the Import and export tab is the quickest way to start a new version.</p>
</x-help-page>
