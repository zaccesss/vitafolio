<x-help-page slug="faq">
    <h2>Is it free?</h2>
    <p>Yes. There are no paid plans and no adverts.</p>

    <h2>How many CVs can I keep?</h2>
    <p>Up to ten, each with its own address and privacy setting.</p>

    <h2>Who can see a private CV?</h2>
    <p>Only you and the site's moderators.</p>

    <h2>Do employers need an account to read my CV?</h2>
    <p>No. Public and unlisted CVs open for anyone with the link.</p>

    <h2>Can I use the CV I already have?</h2>
    <p>Yes. Upload a PDF or Word file, import a JSON Resume file or write one in the LaTeX editor. A CV can have both built content and a file.</p>

    <h2>Can I change my handle?</h2>
    <p>Yes, once every 30 days. Your old handle redirects to the new one for 30 days.</p>

    <h2>What happens if I delete my account?</h2>
    <p>Your profile, CVs, files, photos and connected sign-ins are deleted straight away, including copies held by our file storage provider.</p>

    <h2>Can I take my CV elsewhere?</h2>
    <p>Yes. Export any CV as JSON Resume, an open format other tools can read. You can also download all your data at once from your settings.</p>

    <h2>I found a problem. Where do I report it?</h2>
    <p>Use the <a href="{{ route('contact.show') }}">contact page</a>. Report a CV that breaks the rules with the <strong>Report</strong> button on that CV.</p>
</x-help-page>
