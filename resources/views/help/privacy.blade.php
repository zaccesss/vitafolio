    <p>Set visibility for each CV under <strong>Look and privacy</strong>. Your profile has its own setting under <strong>Settings</strong>, then <strong>Public profile</strong>. A private profile also takes your CVs out of the directory and out of search engines.</p>

    <h2>Your email address</h2>
    <p>Your email address only appears on a CV if you tick <strong>Show my email address</strong> for that CV. Visitors can still message you without it.</p>

    <h2>What visitors leave behind</h2>
    <p>A visit is counted once a day using a code that changes every day, so nobody can follow a visitor from one day to the next. Your own visits are never counted. There are no advertising or tracking cookies.</p>

    <h2>Your data</h2>
    <p>Download everything stored about you or delete your account and every file with it. Both are under <strong>Settings</strong>, then <strong>Your data</strong>. Read the full <a href="{{ route('privacy') }}">privacy policy</a> for the details.</p>
