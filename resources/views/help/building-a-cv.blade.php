    <h2>Sections</h2>
    <p>The Content tab holds a headline for this CV, your main language, a profile summary, experience, education and skills. Leave any section empty and it is left out of the CV.</p>
    <p>A CV can use its own headline. That lets one CV say <em>Embedded software engineer</em> while another says <em>Research assistant</em>, without changing your profile.</p>

    <h2>Skills</h2>
    <p>Type skills separated by commas. Common spellings are joined together, so <em>JS</em> and <em>JavaScript</em> become one skill. Skills on public CVs appear as filters in the directory, which helps people find you.</p>

    <h2>Projects</h2>
    <p>Add up to twelve projects to a CV, each with a title, a link and a description of what you did and what came of it. A project can show one image or one short video (up to 90 seconds). Describe the image or video for people who cannot see it; the description is read aloud by screen readers.</p>

    <h2>Order</h2>
    <p>Drag the sections into the order you want. You can also use the <strong>Move up</strong> and <strong>Move down</strong> buttons. The same order is used on the CV page and in its PDF.</p>

    <h2>Themes, colours and fonts</h2>
    <p>Choose from four themes: Classic, Modern, Minimal and Plain. Plain is built to be read easily by screen readers and by the applicant tracking systems employers use. Every accent colour passes contrast checks in light and dark mode.</p>

    <h2>Import and export</h2>
    <p>Import a <a href="https://jsonresume.org" rel="noopener">JSON Resume</a> file to fill a CV in one step. You can also export any CV in the same open format to use elsewhere.</p>
